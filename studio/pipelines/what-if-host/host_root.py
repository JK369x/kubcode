"""Host integration: register every READY vertical episode as a 1080x1920 composition.

Usage: python3 host_root.py

Writes src/episodes/vertical.generated.tsx in the Remotion project. Episodes come from the folders in
src/episodes/ that have an index.tsx exporting Episode and TOTAL, filtered by the READY file (one slug per line), so a
half-written episode cannot break the bundle. The composition id is the slug in PascalCase (bees-vanish ->
BeesVanish). Root.tsx renders <VerticalEpisodes />.
"""
from __future__ import annotations

from pathlib import Path

from host_lib import ready_episodes, studio_dir


def render(ready: list[tuple[str, str]]) -> str:
    imports = "\n".join(f"import {{ Episode as {c}, TOTAL as {c}Total }} from './{s}';" for s, c in ready)
    comps = "\n".join(
        f'    <Composition id="{c}" component={{{c}}} durationInFrames={{{c}Total}} fps={{30}} width={{1080}} height={{1920}} />'
        for _, c in ready
    )
    return f"""// GENERATED by studio/pipelines/what-if-host/host_root.py from READY. Do not edit by hand.
import React from 'react';
import {{ Composition }} from 'remotion';
{imports}

// Vertical What If shorts (1080 x 1920, 30 fps).
export const VerticalEpisodes: React.FC = () => (
  <>
{comps}
  </>
);
"""


def main() -> None:
    studio = studio_dir()
    ready = ready_episodes(studio)
    out = studio / "src/episodes/vertical.generated.tsx"
    out.write_text(render(ready), encoding="utf-8")
    print("registered:", [c for _, c in ready])


if __name__ == "__main__":
    main()
